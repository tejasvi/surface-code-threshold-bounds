"""mkdata.py: Lean data and check modules for one counting certificate (untrusted generator; Lean checks everything).

usage: python3 -I -B gen/mkdata.py NAME STATES HFILE n K c1,c2,.. Pn Pd Xn Xd Ln Ld K0DEN ROWCHUNKS [RECS_PER_DATA_CHUNK]

Reads a generator's .states (one line per state: K step digits, a space, K labels E/C; ascending keys) and .H
(int64 little endian, same order). Writes, relative to the project root (the current directory):
  QECCountComp/Data/NAME/C<j>.lean   hex records (7 digits key, 9 digits H), as string literals
  QECCountComp/Data/NAME.lean        keysNAME, HsNAME (loaded at initialization), PNAME : Params
  QEC/Checks/NAME/R<j>.lean          rows of a range of states (native_decide)
  QEC/Checks/NAME/D<j>.lean          start completeness from the j-th first step (native_decide)
  QEC/Checks/NAME/S.lean             the number of states and the start sum (native_decide)
  QEC/Checks/NAME/LIST.txt           the check modules, for scripts/run_checks.sh
and prints a JSON summary (input sha256, counts, Hmin, Hmax, exact start constant, the chosen bound K0n/K0d).
Key of a state: digits 2*step + label (C = 1) in base 4n, first edge most significant.
"""
import hashlib
import json
import os
import struct
import sys
from fractions import Fraction


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for blk in iter(lambda: f.read(1 << 20), b""):
            h.update(blk)
    return h.hexdigest()


def main():
    a = sys.argv[1:]
    name, sfile, hfile = a[0], a[1], a[2]
    n, K = int(a[3]), int(a[4])
    c = [int(x) for x in a[5].split(",")]
    Pn, Pd, Xn, Xd, Ln, Ld = (int(x) for x in a[6:12])
    K0den = int(a[12])
    nrow = int(a[13])
    per = int(a[14]) if len(a) > 14 else 500000
    safe = len(a) > 15 and a[15] == "safe"
    rowsF, dfsF = ("rowsOKS", "dfsTopS") if safe else ("rowsOK", "dfsTop")
    B = 4 * n
    keys, nCs = [], []
    with open(sfile) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            ds, ls = line.split()
            assert len(ds) == K and len(ls) == K, line
            k = 0
            for d, l in zip(ds, ls):
                dv = int(d)
                assert 0 <= dv < 2 * n
                assert l in "EC"
                k = k * B + 2 * dv + (1 if l == "C" else 0)
            keys.append(k)
            nCs.append(ls.count("C"))
    raw = open(hfile, "rb").read()
    assert len(raw) == 8 * len(keys), (len(raw), len(keys))
    H = list(struct.unpack("<%dq" % len(keys), raw))
    assert all(keys[i] < keys[i + 1] for i in range(len(keys) - 1)), "keys not ascending"
    assert all(1 <= h < 16 ** 9 for h in H) and all(k < 16 ** 7 for k in keys)
    N = len(keys)
    Hmin, Hmax = min(H), max(H)
    wE, wC, Q = Pn * Xn * Xn, (Pd - Pn) * Xd * Xd, Pd * Xd * Xn
    tot = [0] * (K + 1)
    for h, nc in zip(H, nCs):
        tot[nc] += h
    S = sum(tot[cc] * wE ** (K - cc) * wC ** cc for cc in range(K + 1))
    K0 = Fraction((wE + wC) ** 2 * S, Hmin * Q ** (K + 2))
    K0num = -((-K0.numerator * K0den) // K0.denominator)  # ceil(K0 * K0den)
    assert (wE + wC) ** 2 * S * K0den <= K0num * Hmin * Q ** (K + 2)
    # data chunks
    ddir = os.path.join("QECCountComp", "Data", name)
    os.makedirs(ddir, exist_ok=True)
    nchunks = (N + per - 1) // per
    for j in range(nchunks):
        lo, hi = j * per, min(N, (j + 1) * per)
        body = "".join("%07x%09x" % (keys[i], H[i]) for i in range(lo, hi))
        with open(os.path.join(ddir, "C%d.lean" % j), "w") as f:
            f.write("-- Generated by gen/mkdata.py: certificate %s, records %d..%d (7 hex digits key, 9 hex digits H).\n"
                    % (name, lo, hi - 1))
            f.write("namespace QECComp.Data.%s\n\n" % name)
            f.write("/-- Records %d..%d of certificate %s. -/\n" % (lo, hi - 1, name))
            f.write("def c%d : String := \"%s\"\n\nend QECComp.Data.%s\n" % (j, body, name))
    with open(os.path.join("QECCountComp", "Data", name + ".lean"), "w") as f:
        f.write("import QECCountComp.Load\n")
        if safe:
            f.write("import QECCountComp.Safe\n")
        for j in range(nchunks):
            f.write("import QECCountComp.Data.%s.C%d\n" % (name, j))
        f.write("\n/-!\n# Certificate %s (generated by gen/mkdata.py)\n\n" % name)
        f.write("- states: `%s`, sha256 `%s`\n- potentials: `%s`, sha256 `%s`\n" % (
            os.path.basename(sfile), sha256(sfile), os.path.basename(hfile), sha256(hfile)))
        f.write("- %d states, memory K = %d (windows of up to %d edges), dimension %d, phi coefficients %s\n" % (
            N, K, K + 1, n, c))
        f.write("- p** = %d/%d, X = %d/%d, lambda = %d/%d, Hmin = %d, Hmax = %d\n" % (Pn, Pd, Xn, Xd, Ln, Ld, Hmin, Hmax))
        f.write("- start constant %.10f <= %d/%d\n-/\n\n" % (float(K0), K0num, K0den))
        f.write("namespace QECComp.Data\n\n")
        f.write("/-- The data chunks of certificate %s. -/\ndef data%s : List String := [%s]\n\n" % (
            name, name, ", ".join("%s.c%d" % (name, j) for j in range(nchunks))))
        f.write("/-- The keys and potentials of certificate %s. -/\ndef ld%s : Array Nat × Array Nat := loadData data%s\n\n"
                % (name, name, name))
        f.write("/-- The keys of certificate %s. -/\ndef keys%s : Array Nat := ld%s.1\n\n" % (name, name, name))
        f.write("/-- The potentials of certificate %s. -/\ndef Hs%s : Array Nat := ld%s.2\n\n" % (name, name, name))
        f.write("/-- The parameters of certificate %s. -/\n" % name)
        f.write("def P%s : Params where\n  n := %d\n  c := [%s]\n  K := %d\n  wE := %d\n  wC := %d\n  Q := %d\n"
                "  lamN := %d\n  lamD := %d\n  Hmin := %d\n  K0n := %d\n  K0d := %d\n\n" % (
                    name, n, ", ".join(str(x) for x in c), K, wE, wC, Q, Ln, Ld, Hmin, K0num, K0den))
        f.write("end QECComp.Data\n")
    # check modules
    cdir = os.path.join("QEC", "Checks", name)
    os.makedirs(cdir, exist_ok=True)
    mods = []
    bounds = [N * j // nrow for j in range(nrow + 1)]
    hdr = "import QECCountComp.Data.%s\n\nnamespace QECChecks.%s\n\nopen QECComp QECComp.Data\n\n" % (name, name)
    for j in range(nrow):
        with open(os.path.join(cdir, "R%d.lean" % j), "w") as f:
            f.write(hdr)
            f.write("/-- Rows of the states %d..%d of certificate %s. -/\n" % (bounds[j], bounds[j + 1] - 1, name))
            f.write("theorem rows%d : %s P%s keys%s Hs%s %d %d = true := by\n  native_decide\n\nend QECChecks.%s\n" % (
                j, rowsF, name, name, name, bounds[j], bounds[j + 1], name))
        mods.append("R%d" % j)
    for j in range(4 * n):
        with open(os.path.join(cdir, "D%d.lean" % j), "w") as f:
            f.write(hdr)
            f.write("/-- Start completeness from the candidate step %d, certificate %s. -/\n" % (j, name))
            f.write("theorem dfs%d : %s P%s keys%s %d = true := by\n  native_decide\n\nend QECChecks.%s\n" % (
                j, dfsF, name, name, j, name))
        mods.append("D%d" % j)
    with open(os.path.join(cdir, "S.lean"), "w") as f:
        f.write(hdr)
        f.write("/-- The number of states of certificate %s. -/\n" % name)
        f.write("theorem size : keys%s.size = %d := by\n  native_decide\n\n" % (name, N))
        f.write("/-- The start sum of certificate %s. -/\n" % name)
        f.write("theorem start : startOK P%s keys%s Hs%s = true := by\n  native_decide\n\nend QECChecks.%s\n" % (
            name, name, name, name))
    mods.append("S")
    with open(os.path.join(cdir, "LIST.txt"), "w") as f:
        f.write("\n".join(mods) + "\n")
    print(json.dumps(dict(name=name, states=N, K=K, n=n, Hmin=Hmin, Hmax=Hmax, K0=float(K0), K0n=K0num, K0d=K0den,
                          wE=wE, wC=wC, Q=Q, data_chunks=nchunks, row_chunks=nrow, row_bounds=bounds,
                          states_sha256=sha256(sfile), H_sha256=sha256(hfile))))


main()

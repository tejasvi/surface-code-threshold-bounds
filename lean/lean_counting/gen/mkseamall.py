"""mkseamall.py: the assembly module QEC/Checks/NAME/All.lean of a seam certificate (untrusted generator).

usage: python3 -I -B gen/mkseamall.py NAME

Reads the check modules written by gen/mkseam.py (N<j>, B<j>: entry ranges; D0: offset bigO; D<j>, j >= 1, and
S<j>, j >= 1: ranges of offsets; S: sizes and the start bound at bigO) and writes All.lean with `certOK : CertOKT ...`
(ranges chained by nearRowsOK_append, bulkRowsOK_append, rangeAllT_append').
"""
import os
import re
import sys


def ranges(cdir, pre, pat):
    out = []
    j = 0
    while os.path.exists(os.path.join(cdir, "%s%d.lean" % (pre, j))):
        m = re.search(pat, open(os.path.join(cdir, "%s%d.lean" % (pre, j))).read())
        out.append((int(m.group(1)), int(m.group(2))))
        j += 1
    return out


def main():
    name = sys.argv[1]
    cdir = os.path.join("QEC", "Checks", name)
    args = "P%s nk%s nG%s bk%s bH%s" % ((name,) * 5)
    near = ranges(cdir, "N", r"nearRowsOK P\w+ \w+ \w+ \w+ \w+ (\d+) (\d+) = true")
    bulk = ranges(cdir, "B", r"bulkRowsOK P\w+ \w+ \w+ \w+ \w+ (\d+) (\d+) = true")
    dfs, st = [], []
    j = 1
    while os.path.exists(os.path.join(cdir, "D%d.lean" % j)):
        m = re.search(r"rangeAllT \((-?\d+)\) (\d+) \(dfsOffT", open(os.path.join(cdir, "D%d.lean" % j)).read())
        dfs.append((int(m.group(1)), int(m.group(2))))
        j += 1
    j = 1
    while os.path.exists(os.path.join(cdir, "S%d.lean" % j)):
        m = re.search(r"rangeAllT \((-?\d+)\) (\d+) \(startOKT", open(os.path.join(cdir, "S%d.lean" % j)).read())
        st.append((int(m.group(1)), int(m.group(2))))
        j += 1
    for rs in (near, bulk):
        assert rs and rs[0][0] == 0 and all(rs[i][1] == rs[i + 1][0] for i in range(len(rs) - 1))
    for rs in (dfs, st):
        assert rs and all(rs[i][0] + rs[i][1] == rs[i + 1][0] for i in range(len(rs) - 1))
    assert dfs[0][0] == st[0][0] and sum(c for _, c in dfs) == sum(c for _, c in st)
    lo, tot = dfs[0][0], sum(c for _, c in dfs)
    L = ["import QEC.Count.CertSoundT", "import QEC.Count.ChunksT", "import QEC.Checks.%s.S" % name]
    L += ["import QEC.Checks.%s.N%d" % (name, i) for i in range(len(near))]
    L += ["import QEC.Checks.%s.B%d" % (name, i) for i in range(len(bulk))]
    L += ["import QEC.Checks.%s.D%d" % (name, i) for i in range(len(dfs) + 1)]
    L += ["import QEC.Checks.%s.S%d" % (name, i + 1) for i in range(len(st))]
    L += ["", "/-!\n# Seam certificate %s: assembly of the checks (generated by gen/mkseamall.py)\n-/" % name, "",
          "namespace QECChecks.%s" % name, "", "open QEC QECComp QECComp.Data", ""]

    def chain(thm, fn, rs, size_rw, prefix):
        L.append("theorem %s : %s %s 0 %s = true := by" % (thm, fn, args, size_rw[0]))
        L.append("  rw [%s]" % size_rw[1])
        L.append("  have h0 := %s0" % prefix)
        for i in range(1, len(rs)):
            L.append("  have h%d := %s_append (by norm_num) (by norm_num) h%d %s%d" % (i, fn, i - 1, prefix, i))
        L.append("  exact h%d" % (len(rs) - 1))
        L.append("")

    chain("hnear", "nearRowsOK", near, ("nk%s.size" % name, "sizes.1"), "near")
    chain("hbulk", "bulkRowsOK", bulk, ("bk%s.size" % name, "sizes.2.2.1"), "bulk")

    def chainR(thm, fn, rs, prefix):
        L.append("theorem %s : rangeAllT (-((P%s.HC + P%s.K : ℕ) : ℤ)) (2 * (P%s.HC + P%s.K)) (%s %s) = true := by" % (
            thm, name, name, name, name, fn, args))
        L.append("  have e1 : (-((P%s.HC + P%s.K : ℕ) : ℤ)) = %d := by decide" % (name, name, lo))
        L.append("  have e2 : 2 * (P%s.HC + P%s.K) = %d := by decide" % (name, name, tot))
        L.append("  rw [e1, e2]")
        L.append("  have h1 := %s1" % prefix)
        acc = rs[0][1]
        for i in range(1, len(rs)):
            L.append("  have h%d := rangeAllT_append' (c1 := %d) h%d %s%d (by norm_num)" % (i + 1, acc, i, prefix,
                                                                                         i + 1))
            acc += rs[i][1]
        L.append("  exact h%d" % len(rs))
        L.append("")

    chainR("hdfsNear", "dfsOffT", dfs, "dfs")
    chainR("hstartNear", "startOKT", st, "start")
    L.append("/-- The checks of seam certificate %s. -/" % name)
    L.append("theorem certOK : CertOKT %s where" % args)
    L.append("  hK := by decide")
    L.append("  hHC := by decide")
    L.append("  hQ := by decide")
    L.append("  hlamD := by decide")
    L.append("  sizeG := by rw [sizes.1, sizes.2.1]")
    L.append("  sizeH := by rw [sizes.2.2.1, sizes.2.2.2]")
    L.append("  near := hnear")
    L.append("  bulk := hbulk")
    L.append("  dfsBig := dfs0")
    L.append("  dfsNear := hdfsNear")
    L.append("  startBig := startBig")
    L.append("  startNear := hstartNear")
    L.append("  hK0d := by decide")
    L.append("  hHC2 := by decide")
    L += ["", "end QECChecks.%s" % name]
    with open(os.path.join(cdir, "All.lean"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote %s/All.lean: %d near ranges, %d bulk ranges, %d dfs ranges, %d start ranges" % (
        cdir, len(near), len(bulk), len(dfs), len(st)))


main()

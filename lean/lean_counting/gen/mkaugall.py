"""mkaugall.py: the assembly module QEC/Checks/NAME/All.lean of an augmented certificate (untrusted generator).

usage: python3 -I -B gen/mkaugall.py NAME

Reads the check modules written by gen/mkaug.py (N<j>, I<j>, B<j>: entry ranges; S: sizes and the start bounds;
D<j>: either D0 = dfsHA at bigH and D1.. = rangeAllA over ranges of heights, or, with dfsSplit, one module per height
and range of first steps, `(List.range' a n).all (dfsTopA ... h0)`) and writes All.lean with
`certOK : CertOKA P nk nG bk bH` (QEC/Count/AugDefs.lean), chaining the chunks with the lemmas of
QEC/Count/ChunksA.lean. The start completeness must cover every height 0..HC+K and bigH (no consistOKA modules).
"""
import json
import os
import re
import sys


def ranges(cdir, pre, pat):
    out = []
    j = 0
    while os.path.exists(os.path.join(cdir, "%s%d.lean" % (pre, j))):
        m = re.search(pat, open(os.path.join(cdir, "%s%d.lean" % (pre, j))).read())
        assert m, "%s%d: unexpected statement" % (pre, j)
        out.append((int(m.group(1)), int(m.group(2))))
        j += 1
    return out


def main():
    name = sys.argv[1]
    cdir = os.path.join("QEC", "Checks", name)
    args = "P%s nk%s nG%s bk%s bH%s" % ((name,) * 5)
    A = r"P\w+ \w+ \w+ \w+ \w+"
    near = ranges(cdir, "N", r"nearRowsOKA %s (\d+) (\d+) = true" % A)
    ifr = ranges(cdir, "I", r"ifRowsOKA %s (\d+) (\d+) = true" % A)
    bulk = ranges(cdir, "B", r"bulkRowsOKA %s (\d+) (\d+) = true" % A)
    assert not os.path.exists(os.path.join(cdir, "Q0.lean")), "consistency modules: not covered by CertOKA"
    datf = os.path.join("QECCountComp", "Data", name + ".lean")
    txt = open(datf).read()
    K = int(re.search(r"\n  K := (\d+)\n", txt).group(1))
    HC = int(re.search(r"\n  HC := (\d+)\n", txt).group(1))
    n = HC + K + 1
    sz = re.search(r"nk%s\.size = (\d+) ∧ nG%s\.size = (\d+) ∧ bk%s\.size = (\d+) ∧ bH%s\.size = (\d+)" % (
        (name,) * 4), open(os.path.join(cdir, "S.lean")).read())
    nn, nb = int(sz.group(1)), int(sz.group(3))
    for rs, tot in ((near, nn), (ifr, nb), (bulk, nb)):
        assert rs and rs[0][0] == 0 and rs[-1][1] == tot and all(rs[i][1] == rs[i + 1][0] for i in range(len(rs) - 1))
    # start completeness modules
    dmods = []
    j = 0
    while os.path.exists(os.path.join(cdir, "D%d.lean" % j)):
        dmods.append(open(os.path.join(cdir, "D%d.lean" % j)).read())
        j += 1
    split = any("dfsTopA" in t for t in dmods)
    L = ["import QEC.Count.AugDefs", "import QEC.Count.ChunksA", "import QEC.Checks.%s.S" % name]
    L += ["import QEC.Checks.%s.N%d" % (name, i) for i in range(len(near))]
    L += ["import QEC.Checks.%s.I%d" % (name, i) for i in range(len(ifr))]
    L += ["import QEC.Checks.%s.B%d" % (name, i) for i in range(len(bulk))]
    L += ["import QEC.Checks.%s.D%d" % (name, i) for i in range(len(dmods))]
    L += ["", "/-!\n# Augmented certificate %s: assembly of the checks (generated by gen/mkaugall.py)\n-/" % name, "",
          "namespace QECChecks.%s" % name, "", "open QEC QECComp QECComp.Data", ""]

    def chain(thm, fn, rs, size_rw, prefix):
        L.append("theorem %s : %s %s 0 %s = true := by" % (thm, fn, args, size_rw[0]))
        L.append("  rw [%s]" % size_rw[1])
        L.append("  have h0 := %s0" % prefix)
        for i in range(1, len(rs)):
            L.append("  have h%d := %s_append (by norm_num) (by norm_num) h%d %s%d" % (i, fn, i - 1, prefix, i))
        L.append("  exact h%d" % (len(rs) - 1))
        L.append("")

    chain("hnear", "nearRowsOKA", near, ("nk%s.size" % name, "sizes.1"), "near")
    chain("hif", "ifRowsOKA", ifr, ("bk%s.size" % name, "sizes.2.2.1"), "i")
    chain("hbulk", "bulkRowsOKA", bulk, ("bk%s.size" % name, "sizes.2.2.1"), "b")
    L.append("theorem hn : P%s.HC + P%s.K + 1 = %d := by decide" % (name, name, n))
    L.append("")
    if split:
        parts = {}
        pat = r"theorem dfs(\d+) : \(List\.range' (\d+) (\d+)\)\.all \(dfsTopA %s (bigH|\d+)\) = true" % A
        for j, t in enumerate(dmods):
            m = re.search(pat, t)
            assert m and int(m.group(1)) == j, "D%d: unexpected statement" % j
            parts.setdefault(m.group(4), []).append((int(m.group(2)), int(m.group(3)), j))
        hs = ["bigH"] + [str(h) for h in range(n)]
        assert sorted(parts) == sorted(hs), "heights covered: %s" % sorted(parts)
        for h in hs:
            ps = sorted(parts[h])
            assert ps[0][0] == 0 and all(ps[i][0] + ps[i][1] == ps[i + 1][0] for i in range(len(ps) - 1))
            assert ps[-1][0] + ps[-1][1] == 8
            thm = "hdfsBig" if h == "bigH" else "hdfs%s" % h
            L.append("theorem %s : dfsHA %s %s = true := by" % (thm, args, h))
            L.append("  rw [dfsHA_eq_all]")
            L.append("  have h0 := dfs%d" % ps[0][2])
            for i in range(1, len(ps)):
                L.append("  have h%d := all_range'_append h%d dfs%d" % (i, i - 1, ps[i][2]))
            L.append("  exact h%d" % (len(ps) - 1))
            L.append("")
        L.append("theorem hdfsNear : rangeAllA 0 (P%s.HC + P%s.K + 1) (dfsHA %s) = true := by" % (name, name, args))
        L.append("  rw [hn]")
        L.append("  have h0 := rangeAllA_one (f := dfsHA %s) hdfs0" % args)
        for h in range(1, n):
            L.append("  have h%d := rangeAllA_append' (c1 := %d) h%d (rangeAllA_one (f := dfsHA %s) hdfs%d) "
                     "(by norm_num)" % (h, h, h - 1, args, h))
        L.append("  exact h%d" % (n - 1))
        L.append("")
        big = "hdfsBig"
    else:
        assert re.search(r"theorem dfs0 : dfsHA %s bigH = true" % A, dmods[0]), "D0: unexpected statement"
        rs = []
        for j in range(1, len(dmods)):
            m = re.search(r"theorem dfs%d : rangeAllA (\d+) (\d+) \(dfsHA %s\) = true" % (j, A), dmods[j])
            assert m, "D%d: unexpected statement" % j
            rs.append((int(m.group(1)), int(m.group(2))))
        assert rs[0][0] == 0 and all(rs[i][0] + rs[i][1] == rs[i + 1][0] for i in range(len(rs) - 1))
        assert rs[-1][0] + rs[-1][1] == n, "heights 0..%d not covered" % (n - 1)
        L.append("theorem hdfsNear : rangeAllA 0 (P%s.HC + P%s.K + 1) (dfsHA %s) = true := by" % (name, name, args))
        L.append("  rw [hn]")
        L.append("  have h1 := dfs1")
        acc = rs[0][1]
        for i in range(1, len(rs)):
            L.append("  have h%d := rangeAllA_append' (c1 := %d) h%d dfs%d (by norm_num)" % (i + 1, acc, i, i + 1))
            acc += rs[i][1]
        L.append("  exact h%d" % len(rs))
        L.append("")
        big = "dfs0"
    L.append("/-- The checks of augmented certificate %s. -/" % name)
    L.append("theorem certOK : CertOKA %s where" % args)
    for fld in ("hK", "hHC", "hHC2", "hN0", "hQ", "hlamD", "hK0d"):
        L.append("  %s := by decide" % fld)
    L.append("  near := hnear")
    L.append("  iface := hif")
    L.append("  bulk := hbulk")
    L.append("  dfsBig := %s" % big)
    L.append("  dfsNear := hdfsNear")
    L.append("  start := start")
    L += ["", "end QECChecks.%s" % name]
    with open(os.path.join(cdir, "All.lean"), "w") as f:
        f.write("\n".join(L) + "\n")
    print(json.dumps(dict(name=name, all=os.path.join(cdir, "All.lean"), near_ranges=len(near), if_ranges=len(ifr),
                          bulk_ranges=len(bulk), dfs_modules=len(dmods), dfs_split=split, heights=n)))


main()

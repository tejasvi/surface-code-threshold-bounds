"""mkkdata.py: kernel-route data and check modules for one certificate (untrusted generator; Lean checks everything).

usage: python3 -I -B gen/mkkdata.py NAME STATES HFILE TRANS n K c1,c2,.. Pn Pd Xn Xd Ln Ld K0DEN ROWCHUNKS

Builds the binary search tree of (key, H, mask) over the listed states. mask bit i (candidate i of candList: direction
i // 2, label i % 2) is set when the candidate step keeps the walk self-avoiding and leads to a listed state, but the
generator's transition list (TRANS: int32 from, int32 to, uint8 isE) does not contain it, i.e. its window of K + 1
edges is excluded. Writes:
  QECCountComp/KData/NAME/T<j>.lean   subtrees of at most 512 entries (raw literals)
  QECCountComp/KData/NAME.lean        tNAME : KTree, PNAME : Params
  QEC/KChecks/NAME/R<j>.lean, D<j>.lean, S.lean, LIST.txt   (decide +kernel)
"""
import hashlib
import json
import os
import struct
import sys
from fractions import Fraction


def walk_ok(steps, n):
    p = [0] * n
    seen = {tuple(p)}
    for d in steps:
        q = list(p)
        q[d // 2] += 1 if d % 2 == 0 else -1
        t = tuple(q)
        if t in seen:
            return False
        seen.add(t)
        p = q
    return True


def main():
    a = sys.argv[1:]
    name, sfile, hfile, tfile = a[0], a[1], a[2], a[3]
    n, K = int(a[4]), int(a[5])
    c = [int(x) for x in a[6].split(",")]
    Pn, Pd, Xn, Xd, Ln, Ld = (int(x) for x in a[7:13])
    K0den, nrow = int(a[13]), int(a[14])
    B = 4 * n
    pats, keys, nCs = [], [], []
    for line in open(sfile):
        line = line.strip()
        if not line:
            continue
        ds, ls = line.split()
        p = [(int(d), l == "C") for d, l in zip(ds, ls)]
        k = 0
        for d, l in p:
            k = k * B + 2 * d + (1 if l else 0)
        pats.append(p)
        keys.append(k)
        nCs.append(ls.count("C"))
    N = len(keys)
    H = list(struct.unpack("<%dq" % N, open(hfile, "rb").read()))
    idx = {k: i for i, k in enumerate(keys)}
    incl = [set() for _ in range(N)]
    raw = open(tfile, "rb").read()
    for r in range(len(raw) // 9):
        fr, to, isE = struct.unpack_from("<iiB", raw, 9 * r)
        d, l = pats[to][-1]
        assert l == (isE == 0)
        incl[fr].add((d, l))
    cand = [(d, l) for d in range(2 * n) for l in (False, True)]
    masks = []
    nmask = 0
    for i in range(N):
        m = 0
        for j, x in enumerate(cand):
            u = pats[i] + [x]
            if not walk_ok([y[0] for y in u], n):
                assert x not in incl[i]
                continue
            tk = 0
            for d, l in u[1:]:
                tk = tk * B + 2 * d + (1 if l else 0)
            if tk in idx:
                if x not in incl[i]:
                    m |= 1 << j
                    nmask += 1
            else:
                assert x not in incl[i]
        masks.append(m)
    Hmin = min(H)
    wE, wC, Q = Pn * Xn * Xn, (Pd - Pn) * Xd * Xd, Pd * Xd * Xn
    tot = [0] * (K + 1)
    for h, nc in zip(H, nCs):
        tot[nc] += h
    S = sum(tot[cc] * wE ** (K - cc) * wC ** cc for cc in range(K + 1))
    K0 = Fraction((wE + wC) ** 2 * S, Hmin * Q ** (K + 2))
    K0num = -((-K0.numerator * K0den) // K0.denominator)
    ddir = os.path.join("QECCountComp", "KData", name)
    os.makedirs(ddir, exist_ok=True)
    defs = []

    def lit(x):
        return "(nat_lit %d)" % x

    def full(lo, hi):
        if lo >= hi:
            return "KTree.leaf"
        mid = (lo + hi) // 2
        return "(KTree.node %s %s %s %s %s)" % (full(lo, mid), lit(keys[mid]), lit(H[mid]), lit(masks[mid]),
                                               full(mid + 1, hi))

    def build(lo, hi):
        if hi - lo <= 512:
            nm = "t%d" % len(defs)
            defs.append((nm, full(lo, hi)))
            return "%s.%s" % (name, nm)
        mid = (lo + hi) // 2
        return "(KTree.node %s %s %s %s %s)" % (build(lo, mid), lit(keys[mid]), lit(H[mid]), lit(masks[mid]),
                                               build(mid + 1, hi))

    top = build(0, N)
    per = 40
    nmod = (len(defs) + per - 1) // per
    for j in range(nmod):
        with open(os.path.join(ddir, "T%d.lean" % j), "w") as f:
            f.write("import QECCountComp.Kern\n-- Generated by gen/mkkdata.py: subtrees of certificate %s.\n" % name)
            f.write("namespace QECComp.KData.%s\n\n" % name)
            for nm, body in defs[j * per:(j + 1) * per]:
                f.write("/-- A subtree of certificate %s. -/\ndef %s : KTree :=\n  %s\n\n" % (name, nm, body))
            f.write("end QECComp.KData.%s\n" % name)
    with open(os.path.join("QECCountComp", "KData", name + ".lean"), "w") as f:
        for j in range(nmod):
            f.write("import QECCountComp.KData.%s.T%d\n" % (name, j))
        f.write("\n/-!\n# Certificate %s, kernel form (generated by gen/mkkdata.py)\n\n" % name)
        f.write("%d states, K = %d, p** = %d/%d, X = %d/%d, lambda = %d/%d, Hmin = %d, start constant %.8f <= %d/%d;\n"
                % (N, K, Pn, Pd, Xn, Xd, Ln, Ld, Hmin, float(K0), K0num, K0den))
        f.write("%d mask bits (claimed exclusions of full windows).\n\n" % nmask)
        for path in (sfile, hfile, tfile):
            hsh = hashlib.sha256(open(path, "rb").read()).hexdigest()
            f.write("- `%s`, sha256 `%s`\n" % (os.path.basename(path), hsh))
        f.write("-/\n\n")
        f.write("namespace QECComp.KData\n\n")
        f.write("/-- The listed states of certificate %s. -/\ndef t%s : KTree :=\n  %s\n\n" % (name, name, top))
        f.write("/-- The parameters of certificate %s. -/\n" % name)
        f.write("def P%s : Params where\n  n := %d\n  c := [%s]\n  K := %d\n  wE := %d\n  wC := %d\n  Q := %d\n"
                "  lamN := %d\n  lamD := %d\n  Hmin := %d\n  K0n := %d\n  K0d := %d\n\nend QECComp.KData\n" % (
                    name, n, ", ".join(str(x) for x in c), K, wE, wC, Q, Ln, Ld, Hmin, K0num, K0den))
    cdir = os.path.join("QEC", "KChecks", name)
    os.makedirs(cdir, exist_ok=True)
    hdr = ("import QECCountComp.KData.%s\n\nnamespace QECKChecks.%s\n\nopen QECComp QECComp.KData\n\n"
           "set_option maxRecDepth 1000000\nset_option maxHeartbeats 0\n\n" % (name, name))
    dfs2 = os.environ.get("DFS2", "0") == "1"
    mods = []
    bounds = [N * j // nrow for j in range(nrow + 1)]
    for j in range(nrow):
        with open(os.path.join(cdir, "R%d.lean" % j), "w") as f:
            f.write(hdr + "theorem rows%d : rowsOKK P%s t%s %d %d = true := by\n  decide +kernel\n\nend QECKChecks.%s\n"
                    % (j, name, name, bounds[j], bounds[j + 1], name))
        mods.append("R%d" % j)
    if dfs2:
        for j1 in range(4 * n):
            for j2 in range(4 * n):
                with open(os.path.join(cdir, "D%d_%d.lean" % (j1, j2)), "w") as f:
                    f.write(hdr + "theorem dfs%d_%d : dfsTop2K P%s t%s %d %d = true := by\n  decide +kernel\n\n"
                            "end QECKChecks.%s\n" % (j1, j2, name, name, j1, j2, name))
                mods.append("D%d_%d" % (j1, j2))
    else:
        for j in range(4 * n):
            with open(os.path.join(cdir, "D%d.lean" % j), "w") as f:
                f.write(hdr + "theorem dfs%d : dfsTopK P%s t%s %d = true := by\n  decide +kernel\n\nend QECKChecks.%s\n"
                        % (j, name, name, j, name))
            mods.append("D%d" % j)
    with open(os.path.join(cdir, "S.lean"), "w") as f:
        f.write(hdr + "theorem size : t%s.toList.length = %d := by\n  decide +kernel\n\n" % (name, N))
        f.write("theorem start : startOKK P%s t%s = true := by\n  decide +kernel\n\nend QECKChecks.%s\n" % (
            name, name, name))
    mods.append("S")
    with open(os.path.join(cdir, "LIST.txt"), "w") as f:
        f.write("\n".join(mods) + "\n")
    print(json.dumps(dict(name=name, states=N, mask_bits=nmask, subtrees=len(defs), modules=nmod, K0=float(K0),
                          K0n=K0num, K0d=K0den, Hmin=Hmin, row_bounds=bounds)))


main()

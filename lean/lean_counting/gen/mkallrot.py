"""mkallrot.py: the assembly module QEC/Checks/NAME/All.lean of a SAFE certificate for the rotated code
(untrusted generator).

usage: python3 -I -B gen/mkallrot.py NAME Pn Pd Xn Xd

Writes `hrows` (rowsOKS ranges chained by rowsOKS_append), `hdfs` (dfsTopS over the first steps) and `bound`: the bound
of `rot_bound_of_certS` for every odd distance `d ≥ max(3, K + 2)` and every `0 < p ≤ Pn / Pd`.
"""
import os
import re
import sys


def main():
    name, Pn, Pd, Xn, Xd = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]), int(sys.argv[5])
    cdir = os.path.join("QEC", "Checks", name)
    rows = []
    j = 0
    while os.path.exists(os.path.join(cdir, "R%d.lean" % j)):
        txt = open(os.path.join(cdir, "R%d.lean" % j)).read()
        m = re.search(r"rowsOKS P%s keys%s Hs%s (\d+) (\d+) = true" % (name, name, name), txt)
        rows.append((int(m.group(1)), int(m.group(2))))
        j += 1
    nd = 0
    while os.path.exists(os.path.join(cdir, "D%d.lean" % nd)):
        nd += 1
    assert rows and rows[0][0] == 0 and all(rows[i][1] == rows[i + 1][0] for i in range(len(rows) - 1))
    L = ["import QEC.Count.RotFinal", "import QEC.Count.Chunks", "import Mathlib.Tactic.IntervalCases",
         "import QEC.Checks.%s.S" % name]
    L += ["import QEC.Checks.%s.R%d" % (name, i) for i in range(len(rows))]
    L += ["import QEC.Checks.%s.D%d" % (name, i) for i in range(nd)]
    L += ["", "/-!\n# Certificate %s (SAFE rules): assembly of the native checks (generated by gen/mkallrot.py)\n-/" % name,
          "", "namespace QECChecks.%s" % name, "", "open QEC QECComp QECComp.Data Finset", ""]
    L.append("theorem hrows : ∀ i < keys%s.size, rowCheckS P%s keys%s Hs%s i = true := by" % (name, name, name, name))
    L.append("  rw [size]")
    L.append("  have h0 := rows0")
    for i in range(1, len(rows)):
        L.append("  have h%d := rowsOKS_append (by decide) (by decide) h%d rows%d" % (i, i - 1, i))
    L.append("  exact rowCheckS_of_rowsOKS h%d" % (len(rows) - 1))
    L.append("")
    L.append("theorem hdfs : dfsOKS P%s keys%s P%s.K [] = true := by" % (name, name, name))
    L.append("  apply dfsOKS_of_tops (by decide)")
    L.append("  have hl : (candList P%s.n).length = %d := by decide" % (name, nd))
    L.append("  rw [hl]")
    L.append("  intro j hj")
    L.append("  interval_cases j")
    L.append("  exacts [%s]" % ", ".join("dfs%d" % i for i in range(nd)))
    L.append("")
    L.append("/-- The bound of certificate %s for the rotated code of every odd distance `d ≥ K + 2` and `0 < p ≤ %d/%d`. -/"
             % (name, Pn, Pd))
    L.append("theorem bound (d : ℕ) (hd3 : 3 ≤ d) (hodd : Odd d) (hK : P%s.K + 2 ≤ d) {p : ℝ} (hp0 : 0 < p)" % name)
    L.append("    (hp : p ≤ ((%d : ℕ) : ℝ) / (%d : ℕ)) :" % (Pn, Pd))
    L.append("    PfailRot d p ≤")
    L.append("      2 * d * ((P%s.K0n : ℝ) / P%s.K0d) *" % (name, name))
    L.append("        ((P%s.lamN : ℝ) / P%s.lamD * rhoOf (((%d : ℕ) : ℝ) / (%d : ℕ)) p) ^ (d - 2 - P%s.K) /" % (
        name, name, Pn, Pd, name))
    L.append("          (1 - (P%s.lamN : ℝ) / P%s.lamD * rhoOf (((%d : ℕ) : ℝ) / (%d : ℕ)) p) :=" % (name, name, Pn, Pd))
    L.append("  rot_bound_of_certS P%s keys%s Hs%s rfl d hd3 hodd %d %d %d %d rfl rfl rfl (by norm_num) (by norm_num)" % (
        name, name, name, Pn, Pd, Xn, Xd))
    L.append("    (by norm_num) (by norm_num) (by decide) (by decide) (by decide) (by decide) hrows hdfs start hK hp0 hp")
    L += ["", "end QECChecks.%s" % name]
    with open(os.path.join(cdir, "All.lean"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote %s/All.lean: %d row ranges, %d first steps" % (cdir, len(rows), nd))


main()

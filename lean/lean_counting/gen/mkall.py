"""mkall.py: the assembly module QEC/Checks/NAME/All.lean of a certificate (untrusted generator).

usage: python3 -I -B gen/mkall.py NAME Pn Pd Xn Xd

Reads QEC/Checks/NAME/R<j>.lean (the row ranges) and the number of D<j>.lean modules, and writes All.lean:
`hrows` (the row ranges chained by rowsOK_append), `hdfs` (the first steps), and `bound`, the bound of
`box_bound_of_cert` for every box `N` and axis `a` with `K + 1 ≤ N a` and every `0 < p ≤ Pn / Pd`.
"""
import os
import re
import sys


def main():
    name, Pn, Pd, Xn, Xd = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]), int(sys.argv[5])
    cdir = os.path.join("QEC", "Checks", name)
    rows = []
    j = 0
    while os.path.exists(os.path.join(cdir, "R%d.lean" % j)):
        txt = open(os.path.join(cdir, "R%d.lean" % j)).read()
        m = re.search(r"rowsOK P%s keys%s Hs%s (\d+) (\d+) = true" % (name, name, name), txt)
        rows.append((int(m.group(1)), int(m.group(2))))
        j += 1
    nd = 0
    while os.path.exists(os.path.join(cdir, "D%d.lean" % nd)):
        nd += 1
    assert rows and rows[0][0] == 0 and all(rows[i][1] == rows[i + 1][0] for i in range(len(rows) - 1))
    L = []
    L.append("import QEC.Count.Inst")
    L.append("import Mathlib.Tactic.IntervalCases")
    L.append("import QEC.Checks.%s.S" % name)
    L += ["import QEC.Checks.%s.R%d" % (name, i) for i in range(len(rows))]
    L += ["import QEC.Checks.%s.D%d" % (name, i) for i in range(nd)]
    L.append("")
    L.append("/-!\n# Certificate %s: assembly of the native checks (generated by gen/mkall.py)\n-/" % name)
    L.append("")
    L.append("namespace QECChecks.%s" % name)
    L.append("")
    L.append("open QEC QECComp QECComp.Data Finset")
    L.append("")
    L.append("theorem hrows : ∀ i < keys%s.size, rowCheck P%s keys%s Hs%s i = true := by" % (name, name, name, name))
    L.append("  rw [size]")
    L.append("  have h0 := rows0")
    for i in range(1, len(rows)):
        L.append("  have h%d := rowsOK_append (by decide) (by decide) h%d rows%d" % (i, i - 1, i))
    L.append("  exact rowCheck_of_rowsOK h%d" % (len(rows) - 1))
    L.append("")
    L.append("theorem hdfs : dfsOK P%s keys%s P%s.K [] = true := by" % (name, name, name))
    L.append("  apply dfsOK_of_tops (by decide)")
    L.append("  have hl : (candList P%s.n).length = %d := by decide" % (name, nd))
    L.append("  rw [hl]")
    L.append("  intro j hj")
    L.append("  interval_cases j")
    L.append("  exacts [%s]" % ", ".join("dfs%d" % i for i in range(nd)))
    L.append("")
    L.append("/-- The bound of certificate %s for every box with `K + 1 ≤ N a` and every `0 < p ≤ %d/%d`. -/" % (name, Pn, Pd))
    L.append("theorem bound (N : Fin P%s.n → ℕ) (a : Fin P%s.n) (hK : P%s.K + 1 ≤ N a) {p : ℝ} (hp0 : 0 < p)" % (
        name, name, name))
    L.append("    (hp : p ≤ ((%d : ℕ) : ℝ) / (%d : ℕ)) :" % (Pn, Pd))
    L.append("    PfailMW (boxEdges P%s.n N a) p ≤" % name)
    L.append("      #(univ.filter (fun u : BoxV P%s.n N => (u a : ℕ) = 0)) * ((P%s.K0n : ℝ) / P%s.K0d) *" % (
        name, name, name))
    L.append("        ((P%s.lamN : ℝ) / P%s.lamD * rhoOf (((%d : ℕ) : ℝ) / (%d : ℕ)) p) ^ (N a - 1 - P%s.K) /" % (
        name, name, Pn, Pd, name))
    L.append("          (1 - (P%s.lamN : ℝ) / P%s.lamD * rhoOf (((%d : ℕ) : ℝ) / (%d : ℕ)) p) :=" % (name, name, Pn, Pd))
    L.append("  box_bound_of_cert P%s keys%s Hs%s N a %d %d %d %d rfl rfl rfl (by norm_num) (by norm_num) (by norm_num)" % (
        name, name, name, Pn, Pd, Xn, Xd))
    L.append("    (by norm_num) (by decide) (by decide) (by decide) (by decide) (by decide) hrows hdfs start hK hp0 hp")
    L.append("")
    L.append("end QECChecks.%s" % name)
    with open(os.path.join(cdir, "All.lean"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote %s/All.lean: %d row ranges, %d first steps" % (cdir, len(rows), nd))


main()

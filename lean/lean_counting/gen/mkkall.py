"""mkkall.py: the assembly module QEC/KChecks/NAME/All.lean of a kernel-route certificate (untrusted generator).

usage: python3 -I -B gen/mkkall.py NAME Pn Pd Xn Xd

Reads QEC/KChecks/NAME/R<j>.lean (the entry ranges) and the number of D<j>.lean modules, and writes All.lean:
`hrows` (ranges chained by rowsOKK_append), `hdfs` (the first steps), and `bound` (box_bound_of_certK).
"""
import os
import re
import sys


def main():
    name, Pn, Pd, Xn, Xd = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]), int(sys.argv[5])
    cdir = os.path.join("QEC", "KChecks", name)
    rows = []
    j = 0
    while os.path.exists(os.path.join(cdir, "R%d.lean" % j)):
        txt = open(os.path.join(cdir, "R%d.lean" % j)).read()
        m = re.search(r"rowsOKK P%s t%s (\d+) (\d+) = true" % (name, name), txt)
        rows.append((int(m.group(1)), int(m.group(2))))
        j += 1
    nd = 0
    while os.path.exists(os.path.join(cdir, "D%d.lean" % nd)):
        nd += 1
    # depth-2 start chunks D<j1>_<j2> (gen/mkkdata.py with DFS2=1)
    nd2 = 0
    while os.path.exists(os.path.join(cdir, "D%d_0.lean" % nd2)):
        nd2 += 1
    assert (nd > 0) != (nd2 > 0)
    assert all(os.path.exists(os.path.join(cdir, "D%d_%d.lean" % (a, b))) for a in range(nd2) for b in range(nd2))
    dmods = ["D%d" % i for i in range(nd)] + ["D%d_%d" % (a, b) for a in range(nd2) for b in range(nd2)]
    assert rows and rows[0][0] == 0 and all(rows[i][1] == rows[i + 1][0] for i in range(len(rows) - 1))
    L = ["import QEC.Count.FinalK", "import QEC.Count.Inst", "import Mathlib.Tactic.IntervalCases",
         "import QEC.KChecks.%s.S" % name]
    if nd2:
        L.append("import QEC.Count.ChunksK2")
    L += ["import QEC.KChecks.%s.R%d" % (name, i) for i in range(len(rows))]
    L += ["import QEC.KChecks.%s.%s" % (name, d) for d in dmods]
    L += ["", "/-!\n# Certificate %s (kernel route): assembly of the kernel checks (generated by gen/mkkall.py)\n-/" % name,
          "", "namespace QECKChecks.%s" % name, "", "open QEC QECComp QECComp.KData Finset", ""]
    L.append("theorem hrows : ∀ e ∈ t%s.toList, rowCheckK P%s t%s e = true := by" % (name, name, name))
    L.append("  apply rowCheckK_of_rowsOKK")
    L.append("  rw [size]")
    L.append("  have h0 := rows0")
    for i in range(1, len(rows)):
        L.append("  have h%d := rowsOKK_append (by decide) (by decide) h%d rows%d" % (i, i - 1, i))
    L.append("  exact h%d" % (len(rows) - 1))
    L.append("")
    L.append("theorem hdfs : dfsOKK P%s t%s P%s.K [] = true := by" % (name, name, name))
    if nd2:
        L.append("  apply dfsOKK_of_tops2 (by decide)")
        L.append("  have hl : (candList P%s.n).length = %d := by decide" % (name, nd2))
        L.append("  rw [hl]")
        L.append("  intro j1 hj1 j2 hj2")
        L.append("  interval_cases j1 <;> interval_cases j2")
        L.append("  exacts [%s]" % ", ".join("dfs%d_%d" % (a, b) for a in range(nd2) for b in range(nd2)))
    else:
        L.append("  apply dfsOKK_of_tops (by decide)")
        L.append("  have hl : (candList P%s.n).length = %d := by decide" % (name, nd))
        L.append("  rw [hl]")
        L.append("  intro j hj")
        L.append("  interval_cases j")
        L.append("  exacts [%s]" % ", ".join("dfs%d" % i for i in range(nd)))
    L.append("")
    L.append("/-- The bound of certificate %s (kernel route) for every box with `K + 1 ≤ N a` and `0 < p ≤ %d/%d`. -/"
             % (name, Pn, Pd))
    L.append("theorem bound (N : Fin P%s.n → ℕ) (a : Fin P%s.n) (hK : P%s.K + 1 ≤ N a) {p : ℝ} (hp0 : 0 < p)" % (
        name, name, name))
    L.append("    (hp : p ≤ ((%d : ℕ) : ℝ) / (%d : ℕ)) :" % (Pn, Pd))
    L.append("    PfailMW (boxEdges P%s.n N a) p ≤" % name)
    L.append("      #(univ.filter (fun u : BoxV P%s.n N => (u a : ℕ) = 0)) * ((P%s.K0n : ℝ) / P%s.K0d) *" % (
        name, name, name))
    L.append("        ((P%s.lamN : ℝ) / P%s.lamD * rhoOf (((%d : ℕ) : ℝ) / (%d : ℕ)) p) ^ (N a - 1 - P%s.K) /" % (
        name, name, Pn, Pd, name))
    L.append("          (1 - (P%s.lamN : ℝ) / P%s.lamD * rhoOf (((%d : ℕ) : ℝ) / (%d : ℕ)) p) :=" % (name, name, Pn, Pd))
    L.append("  box_bound_of_certK P%s t%s N a %d %d %d %d rfl rfl rfl (by norm_num) (by norm_num) (by norm_num)" % (
        name, name, Pn, Pd, Xn, Xd))
    L.append("    (by norm_num) (by decide) (by decide) (by decide) (by decide) (by decide) hrows hdfs start hK hp0 hp")
    L += ["", "end QECKChecks.%s" % name]
    with open(os.path.join(cdir, "All.lean"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote %s/All.lean: %d entry ranges, %d start chunks" % (cdir, len(rows), len(dmods)))


main()
